def rel(p: Path) -> str:
    return str(Path(p).resolve().relative_to(ROOT))


def write_csv(path: Path, header, rows) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    for r in rows:
        w.writerow([f"{x:.6g}" if isinstance(x, float) else x for x in r])
    path.write_text(buf.getvalue())


def read_csv(path: Path) -> list[dict]:
    return list(csv.DictReader(path.read_text().splitlines()))


def write_md(path: Path, title: str, sources: list[str], header, rows, notes=()) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    out = [f"# {title}", "", "Generated by `python scripts/paper/make_paper.py "
           f"{path.stem}`. Sources: " + "; ".join(f"`{s}`" for s in sources) + ".", "",
           "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(f"{x:.6g}" if isinstance(x, float) else str(x)
                                     for x in r) + " |")
    if notes:
        out += ["", *notes]
    path.write_text("\n".join(out) + "\n")
    write_csv(path.with_suffix(".csv"), header, rows)


