@item
def F9(out: Path) -> None:
    """Rental 2's launch-floor rerun: per (model, mode, arm, n) the median ms_p50 over
    repeats (cells.csv), H_pre (hostprobe.csv) and C_reg (the registration JSON),
    Granite-3B and tp8."""
    reg = json.loads((REG / "2026-10-01-rental2-launch2-gh200.json").read_text())
    creg = reg["C_reg_ms"]
    base = R2 / "results/2026-10-02-nvidia_gh200_480gb-launch-floor-r2"
    rows = []
    for model in ("granite-3.0-3b-a800m", "mixtral-8x7b-tp8"):
        cells = read_csv(base / model / "cells.csv")
        hp = {(r["mode"], r["arm"], int(r["tiles"])): float(r["H_pre_ms"])
              for r in read_csv(base / model / "hostprobe.csv") if r["H_pre_ms"]}
        keys = sorted({(r["mode"], r["arm"], int(r["tiles"])) for r in cells})
        for mode, arm, n in keys:
            v = [float(r["ms_p50"]) for r in cells
                 if (r["mode"], r["arm"], int(r["tiles"])) == (mode, arm, n) and r["ms_p50"]]
            c = _creg(creg, model, arm, n)
            rows.append((model, mode, arm, n, statistics.median(v), hp.get((mode, arm, n), ""),
                         c))
    write_csv(out / "data/F9.csv", ["model", "mode", "arm", "n", "ms_p50_median", "H_pre_ms",
                                    "C_reg_ms"], rows)


def _creg(creg, model, arm, n):
    m = creg.get(model) if isinstance(creg, dict) else None
    if isinstance(m, dict):
        a = m.get(arm)
        if isinstance(a, list) and n - 1 < len(a):
            return a[n - 1]
        if isinstance(a, dict):
            return a.get(str(n), "")
    return ""


