def plot(name: str, out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig = globals()[f"plot_{name}"](out, plt)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    fig.savefig(out / "figures" / f"{name}.png", dpi=110, metadata={"Software": None})
    plt.close(fig)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("item", choices=[*ITEMS, "all"])
    ap.add_argument("--out", type=Path, default=ROOT / "docs/paper")
    ap.add_argument("--plot", action="store_true", help="also draw the figure (F items)")
    ap.add_argument("--repo", type=Path, default=None,
                    help="T3 only: the git checkout whose history dates the commits")
    a = ap.parse_args(argv)
    for name in (ITEMS if a.item == "all" else [a.item]):
        if name == "T3":
            T3(a.out, a.repo)
        else:
            ITEMS[name](a.out)
        if a.plot and name.startswith("F"):
            plot(name, a.out)
        print(f"{name}: written under {a.out}")
    return 0


