def _old_build(pages, p_knee):
    import r3_timing_model as TM
    argv = [*map(str, pages), "--counters", str(C27), "--p-knee", str(p_knee),
            "--no-tail", "--no-dead", "--no-cta-fixed", "--no-cores"]
    return TM.build(TM.build_parser().parse_args(argv))


import contextlib  # noqa: E402


@contextlib.contextmanager
def _old_model():
    """Hold r3_timing_model's switches at the knee's commit (8900699) while pricing
    outside `build`, which restores them on return."""
    import r3_timing_model as TM
    saved = (TM.P_KNEE, TM.TAIL, TM.DEAD, TM.CTA_FIXED, TM.CORES)
    TM.TAIL = TM.DEAD = TM.CTA_FIXED = TM.CORES = False
    try:
        yield
    finally:
        TM.P_KNEE, TM.TAIL, TM.DEAD, TM.CTA_FIXED, TM.CORES = saved


def _p27_1710():
    import r3_timing_model as TM
    return [p.path for p in TM.discover_timed([S27 / "results"])
            if p.label == "VALID" and p.locked and next(iter(p.clocks)) == 1710.0]


@item
def F2(out: Path) -> None:
    """Soft against hard max on the 2026-09-27 board. Two refits of
    `r3_timing_model.build` on its VALID lock-1710 timed pages and lock-1710 counter
    pages, the model as at the knee's commit 8900699 (--no-tail --no-dead
    --no-cta-fixed --no-cores), at p = 14 and p = inf: per cell measured and both
    predictions. Plus, at G = 3 n = 2, every live w1 CTA's m / f (its window's DRAM
    time over its floor) at the p = 14 fit's c and bw. Writes F2.csv (cells) and
    F2_mf.csv (CTAs)."""
    import r3_timing_model as TM
    pages = _p27_1710()
    soft, hard = _old_build(pages, 14.0), _old_build(pages, math.inf)
    rows = []
    with _old_model():
        for cs, ch in zip(soft["cells"], hard["cells"], strict=True):
            assert cs.key == ch.key
            TM.P_KNEE = 14.0
            ps = TM.call_ms(soft["main"].x, cs, soft["ctx"], soft["k_w"])
            TM.P_KNEE = math.inf
            ph = TM.call_ms(hard["main"].x, ch, hard["ctx"], hard["k_w"])
            rows.append((cs.arm, cs.G, cs.n, int(cs.fit), cs.ms, ps, ph))
    write_csv(out / "data/F2.csv", ["arm", "G", "n", "fitted", "measured_ms", "p14_ms",
                                    "pinf_ms"], rows)
    ctx, x = soft["ctx"], soft["main"].x
    c_ns, bw = float(x[1]), float(x[2])
    mf = []
    for cell in soft["cells"]:
        if (cell.G, cell.n) != (3, 2):
            continue
        g = "w1"
        w = TM.window_width(soft["k_w"], ctx.sms, ctx.occupancy[g])
        win = TM.window(cell.arm, cell.declared, 3, 2, g, w)
        with TM.cta_fixed(False):
            f = TM.wave_q(win.live, ctx.sms) * TM.floor_ksteps(g) * c_ns * 1e-6 / ctx.sms
        m = (cell.sigma[g] * win.mean + TM.OUT_TILE) / (bw * 1e6)
        mf += [(cell.arm, i, float(v)) for i, v in enumerate(m / f)]
    write_csv(out / "data/F2_mf.csv", ["arm", "cta", "m_over_f"], mf)


def plot_F2(out: Path, plt):
    d = read_csv(out / "data/F2_mf.csv")
    fig, ax = plt.subplots(figsize=(5, 3))
    for arm in ("native", "shared", "private"):
        v = [float(r["m_over_f"]) for r in d if r["arm"] == arm]
        ax.hist(v, bins=50, histtype="step", label=arm)
    ax.set_xlabel("m / f per CTA, G = 3, n = 2, w1")
    ax.legend()
    fig.tight_layout()
    return fig


