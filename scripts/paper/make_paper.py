@item
def F1(out: Path) -> None:
    """pid-to-tile launch order at G = 1, 2, 4, Mixtral 8x7B (E 8), n = 3, w2, SHARED
    (72 declared slots): every LIVE CTA in launch order, its (pid_m, pid_n), the
    expert that owns its slab and whether it fetches the slab (the first live CTA of
    its (group, slab key)). Walk: `wave_split_bytes.pid_map`; grid rows from the
    2026-09-27 lock-1710 counter pages r3c-g{1,2,4}.json (`per_gemm.w2.grid_size`)."""
    import wave_split_bytes as WSB
    rows = []
    for G in (1, 2, 4):
        page = json.loads((C27 / f"r3c-g{G}.json").read_text())
        cell = next(c for c in page["cells"] if c["arm"] == "shared" and int(c["n"]) == 3)
        grid = int(cell["per_gemm"]["w2"]["grid_size"])
        npn = 64
        pid = np.arange(grid)
        _gid, pm, pn = WSB.pid_map(pid, grid // npn, npn, G)
        live = pm < 8 * 3
        seen = set()
        rank = 0
        for i in np.nonzero(live)[0]:
            m, nn = int(pm[i]), int(pn[i])
            key = (int(i) // (G * npn), m // 3, nn)
            lead = key not in seen
            seen.add(key)
            rows.append((G, rank, int(i), m, nn, m // 3, int(lead)))
            rank += 1
    write_csv(out / "data/F1.csv", ["G", "live_rank", "pid", "pid_m", "pid_n", "expert",
                                    "fetcher"], rows)


