def F10(out: Path) -> None:
    """Duration against cycles for rental 2's tp4 floor captures at 1005 and 1710:
    per cell and GEMM `gpu__time_duration.sum`, `sm__cycles_elapsed.avg` and
    `lts__cycles_elapsed.avg`, with the least-squares fits duration = t0 + cycles / f
    for SM and L2 cycles per capture (the fit FL1 used; the gate audit's refit)."""
    rows, fits = [], []
    for cap in ("2026-10-02-nvidia_gh200_480gb-mixtral-8x7b-tp4-floor-r3-counters/r3f-g64-lock1710.json",
                "2026-10-02-nvidia_gh200_480gb-mixtral-8x7b-tp4-floor1005-r3-counters/r3f-g64-lock1005.json"):
        p = R2 / "results" / cap
        d = json.loads(p.read_text())
        lock = d["clock"]["lock_mhz"]
        for g in ("w1", "w2"):
            pts = []
            for c in d["cells"]:
                pg = c["per_gemm"].get(g)
                if not pg:
                    continue
                t, sm, lt = (pg.get("gpu__time_duration.sum"), pg.get("sm__cycles_elapsed.avg"),
                             pg.get("lts__cycles_elapsed.avg"))
                rows.append((lock, g, c["n"], t, sm, lt))
                pts.append((t, sm, lt))
            for k, name in ((1, "sm"), (2, "l2")):
                xs = [q[k] for q in pts if q[k]]
                ys = [q[0] for q in pts if q[k]]
                b, t0 = np.polyfit(xs, ys, 1)
                fits.append((lock, g, name, 1e3 / b, t0 / 1e3))
    write_csv(out / "data/F10.csv", ["lock_mhz", "gemm", "n", "duration_ns", "sm_cycles",
                                     "l2_cycles"], rows)
    write_csv(out / "data/F10_fits.csv", ["lock_mhz", "gemm", "cycles", "f_mhz", "t0_us"], fits)


