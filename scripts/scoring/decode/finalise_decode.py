#!/usr/bin/env python
"""The blind rental's predictions, finalised MECHANICALLY from the CAL score (registration
2026-10-14-decodeB-blind-gh200), and both decode plans from one generator.

    python scripts/scoring/decode/finalise_decode.py <CAL score dir> <out.json> [--plan-out <plan file>]
    python scripts/scoring/decode/finalise_decode.py --cal-plan <plan file>      # the CAL plan (committed)

REFUSES (exit 2, nothing written) unless the CAL score's STOP reads GO, and when its fit selected no
rho form. Reads cal.score.json and applies the registered rules, nothing else:
  constants   T0_GR, s_naive_GR, s_block_GR of the selected rho form; the tile stage's v4 Params as
              the CAL scorer used them (tile_params_dict)
  bars        REP's tightened bars (the provisional ones when the replicate was lost)
  GD2         the CAL band, frozen
  G3-D        the CAL margin rule (applied per blind page)
  rivals      eager, roofline, line and OLS (their CAL fits), NAIVE-NODEDUP, the other rho form
and writes, per blind main-page NATIVE cell, v4d's time and every rival's.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import dcommon as DC  # noqa: E402

RD, V4, V4D = DC.RD, DC.V4, DC.V4D
CAL_PLAN = "scripts/plans/rentalD-cal-2026-10.plan"
BLIND_PLAN = "scripts/plans/rentalD-blind-2026-10.plan"


class Refused(Exception):
    pass


def _cap(est: int) -> int:
    return max(15, 3 * est)


def plan_text(units, header: list[str], *, census: bool) -> str:
    """A decode plan from a registered unit list, in its order (the driver drops the last first)."""
    lines = list(header) + ["- prelude est=3 cap=15", "mixtral-8x7b calibrate label=dcal nodrop=1 est=2 cap=30"]
    if census:
        lines.append(f"- tilecensus label=dec tiles={','.join(DC.DECODE_TILES)} models="
                     f"{','.join(DC.CAL_MODELS + DC.BLIND_MODELS)} nodrop=1 est=6 cap=25")
    for label, model, kind, step, inst, drop, est in units:
        d = "nodrop=1" if drop == "nodrop" else f"drop-group={drop}"
        page = DC.page_path(model, kind)
        if step == "r3decode":
            lines.append(f"{model} r3decode label={label} histogram={page} inst={inst} slip-policy=cell "
                         f"g1-rule=r7-median-run3 {d} est={est} cap={_cap(est)}")
        else:
            lines.append(f"{model} decodebytes label={label} histogram={page} {d} est={est} cap={_cap(est)}")
    return "\n".join(lines) + "\n"


def cal_plan() -> str:
    hdr = ["# THE DECODE STAGE'S CAL RENTAL (2026-10-14): vLLM's decode call on OLMoE-1B-7B and Mixtral-8x7B.",
           "# GENERATED by scripts/scoring/decode/finalise_decode.py --cal-plan from registration 2026-10-14-decodeC-cal-gh200;",
           "# do not edit by hand. One gpu_1x_gh200 at $2.29/h, run by the decode stage's driver:",
           "#   bash scripts/vm_run.sh start --ip <ip> --run-id <id> --deadline <epoch s> \\",
           f"#     --plan {CAL_PLAN} --driver gh200_decode_session.sh",
           "# Runs after the tile stage's rental B (owner decision DD6). Drop order, last first: rep, decl, ncu, e240;",
           "# every main (GRR) and ctl (GR1) page is nodrop. A SKIPPED or LOST nodrop unit is a STOP for the blind rental."]
    return plan_text(DC.CAL_UNITS, hdr, census=True)


def blind_plan(fz: dict | None = None) -> str:
    hdr = ["# THE DECODE STAGE'S BLIND RENTAL: v4d frozen, five models no decode page has timed",
           "# (registration 2026-10-14-decodeB-blind-gh200).",
           "# GENERATED by scripts/scoring/decode/finalise_decode.py from the frozen unit list; do not edit by hand.",
           f"# Run by the decode driver: bash scripts/vm_run.sh start ... --plan {BLIND_PLAN} --driver gh200_decode_session.sh",
           "# Drop order, last first: gr1 (the two GR1 control pages); every main page is nodrop."]
    if fz:
        c = fz["constants"]
        us = lambda v: "NOT FITTED" if v is None else f"{v * 1e3:.2f} us"
        hdr.append(f"# Finalised: T0_GR {us(c['T0_GR_ms'])}, s_naive {us(c['s_naive_GR_ms'])}, "
                   f"s_block {us(c['s_block_GR_ms'])}, rho {fz['rho_form']}, bars {fz['bars']}.")
    return plan_text(DC.BLIND_UNITS, hdr, census=False)


def frozen(cal: dict) -> dict:
    st_ = (cal.get("STOP") or {}).get("verdict", "no CAL score")
    if st_ != "GO":
        raise Refused(f"the CAL stop rule reads {st_}: the blind rental does not run "
                      f"({'; '.join((cal.get('STOP') or {}).get('why') or [])})")
    sel = (cal.get("FIT") or {}).get("selected")
    if sel is None:
        raise Refused("the CAL fit selected no rho form")
    fit = cal["FIT"]["forms"][sel]
    tdict = dict(cal.get("tile_params_dict") or {})
    return {"rho_form": sel,
            "constants": {k: fit[k] for k in ("T0_GR_ms", "s_naive_GR_ms", "s_block_GR_ms")},
            "tile_params": tdict, "bars": (cal.get("REP") or {}).get("bars_blind") or DC.tighten(None),
            "sigma_page": (cal.get("REP") or {}).get("sigma_page"),
            "gd2_band_us": (cal.get("GD2") or {}).get("band_us"),
            "g3d_margin_rule": f"max({DC.G3D_US} us, {DC.G3D_REL:.2%} x the median reference time)",
            "rival_fits": cal.get("RIVAL_FITS") or {}}


def params_of(fz: dict, **over) -> V4D.DecodeParams:
    t = V4.Params(**fz["tile_params"]) if fz["tile_params"] else V4.Params()
    d = dict(T0_GR_ms=fz["constants"]["T0_GR_ms"], s_naive_GR_ms=fz["constants"]["s_naive_GR_ms"],
             s_block_GR_ms=fz["constants"]["s_block_GR_ms"], rho_form=fz["rho_form"], tile=t)
    d.update(over)
    return V4D.DecodeParams(**d)


def ols_predict(fit: dict, x: list[float]) -> float | None:
    if fit.get("verdict") != "FITTED":
        return None
    z = [(x[i] - fit["mu"][i]) / fit["sd"][i] for i in range(len(x))]
    return fit["a"] + sum(z[i] * fit["beta"][i] for i in range(len(x)))


def predict(fz: dict, models=DC.BLIND_MODELS, kind: str = "main") -> list[dict]:
    import score_cal as SC
    prm = params_of(fz)
    other = params_of(fz, rho_form="scaled" if fz["rho_form"] == "fixed" else "fixed")
    nodedup = params_of(fz, naive_dedup=False)
    eager = V4D.eager_params(prm)
    line = fz["rival_fits"].get("line") or {}
    ols = fz["rival_fits"].get("OLS") or {}
    out = []
    for m in models:
        doc = DC.page_doc(m, kind)
        for c in doc["cells"]:
            p = DC.price_cell(m, c, prm)
            row = {"model": m, "page": f"{m}-{kind}", "label": c["label"], "T": c["T"], "role": c["role"],
                   "counts_sha256": RD.counts_sha256(c["counts"])}
            if p is None:
                row.update(ms={"v4d": None}, why="NOT PRICED (no tile-stage constants for the wgmma decode tile, or no fitted offset for its path)")
                out.append(row)
                continue
            ms = {"v4d": p["ms"]}
            for name, pp in (("rho other", other), ("NAIVE-NODEDUP", nodedup), ("eager", eager)):
                q = DC.price_cell(m, c, pp)
                ms[name] = None if q is None else q["ms"]
            ms["roofline"] = V4D.roofline_ms(m, c["T"], c["counts"], fz["constants"]["T0_GR_ms"])
            ms["line"] = (line["a_ms"] + line["b_ms_per_row"] * p["numel"]) if line.get("verdict") == "FITTED" else None
            ms["OLS"] = ols_predict(ols, SC.features(p))
            row.update(ms=ms, path=p["path"], tile=p["tile"], A=p["A"], sub_wave=p["sub_wave"])
            out.append(row)
    return out


def finalise(score_dir: Path) -> dict:
    cal = json.loads((Path(score_dir) / "cal.score.json").read_text())
    fz = frozen(cal)
    rows = predict(fz)
    return {"what": "the blind rental's predictions, finalised mechanically from the CAL score (decodeB-blind)",
            "frozen": fz, "cells": rows, "not_priced": sum(1 for r in rows if r["ms"]["v4d"] is None)}


def main(argv=None) -> int:
    a = list(argv if argv is not None else sys.argv[1:])
    if a[:1] == ["--cal-plan"] and len(a) == 2:
        Path(a[1]).write_text(cal_plan())
        print(f"wrote {a[1]}")
        return 0
    plan_out = None
    if "--plan-out" in a:
        i = a.index("--plan-out")
        plan_out = Path(a[i + 1])
        del a[i:i + 2]
    if len(a) != 2:
        print(__doc__)
        return 2
    try:
        doc = finalise(Path(a[0]))
    except Refused as exc:
        print(f"REFUSED: {exc}")
        return 2
    Path(a[1]).write_text(json.dumps(doc, indent=1, default=str) + "\n")
    print(f"wrote {a[1]}: {len(doc['cells'])} cells, {doc['not_priced']} not priced, rho {doc['frozen']['rho_form']}")
    if plan_out is not None:
        plan_out.write_text(blind_plan(doc["frozen"]))
        print(f"wrote {plan_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
