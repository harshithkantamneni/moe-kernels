#!/usr/bin/env python
"""The new blind rental's predictions under the sixth addendum (registration 2026-11-10-decode-addendum6-gh200),
finalised MECHANICALLY from the readings and the published CAL2 tree by the registered rules.

    python scripts/scoring/decode/finalise_decode_d6.py <readings dir> <CAL2 results tree> \\
        <decode blind results tree> <out.json> [--plan-out scripts/plans/rentalD6-blind-2026-11.plan]

REFUSES (exit 2, nothing written) unless the launch gate (gate_d6.evaluate, the same code the operator runs) reads GO:
the readings give the registered v6d, both published trees reproduce their committed scores, CAL2 under v6d reads GO
by the addendum-3 stop rule, and the SEEN decode blind re-scored under v6d reads a pooled rms under 4.0% over its 220
cells (a weak sanity floor on seen pages, never a test). Then exactly finalise_decode's rules (frozen:
finalise_decode.frozen and .predict) with v6d pricing every cell, on addendum 5's registered pages of the three new
models. WHAT IT FREEZES: the model (v6d: v4d''s fixes W and R, v5d's CALL, ALIGN and SLOPE, the registered law), the
three constants and the rho form of the CAL2 refit under v6d, the tile stage's v4 Params as the CAL2 scorer used them,
the OWNER's bars (3% rms, 8% worst, 1.5% |mean|; not tightened), sigma_page, the GD2 band, the G3-D margin rule, the
rivals' CAL2 fits under v6d, the G3-D rule (shuffle voids; label DESCRIPTIVE), the scope line (d3common.SCOPE) and the
blind plan (addendum 5's registered unit lines under an addendum-6 header).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import d2common as D2  # noqa: E402
import d3common as D3  # noqa: E402
import d5common as D5  # noqa: E402
import d6common as D6  # noqa: E402
import finalise_decode as FN  # noqa: E402

Refused = FN.Refused
V4DP, V5D, V6D = D3.V4DP, D5.V5D, D6.V6D

PLAN_HDR = ["# THE DECODE STAGE'S NEW BLIND RENTAL under the sixth addendum: v6d frozen from PC's, PC2's and DS's readings and",
            f"# CAL2, three models no decode page has timed (registration {D6.NAME}; pages and units of addendum 5). GENERATED by",
            "# scripts/scoring/decode/finalise_decode_d6.py, which refuses unless gate_d6.py reads GO; do not edit by hand.",
            "# Run by the pinned decode driver: bash scripts/vm_run.sh start ... --plan "
            f"{D6.BLIND6_PLAN} --driver {D5.BLIND_DRIVER}",
            "# Drop order, last first: gr1 (the two GR1 control pages); every main page is nodrop.",
            "# LAUNCH PRECONDITION: scripts/scoring/decode/gate_d6.py prints GO (both clauses). The last decode blind under",
            "# the owner's stopping rule (2026-11-10): decode closes after it whatever it reads."]


def blind_plan(fz: dict | None = None) -> str:
    """Addendum 5's registered unit lines under this addendum's header (and the finalised constants)."""
    hdr = list(PLAN_HDR)
    if fz:
        c = fz["constants"]
        us = lambda v: "NOT FITTED" if v is None else f"{v * 1e3:.2f} us"  # noqa: E731
        hdr.append(f"# Finalised: T0_GR {us(c['T0_GR_ms'])}, s_naive {us(c['s_naive_GR_ms'])}, s_block {us(c['s_block_GR_ms'])}, "
                   f"rho {fz['rho_form']}, bars rms {fz['bars']['rms_max']:.1%}, worst {fz['bars']['max_abs']:.1%}, "
                   f"mean {fz['bars']['mean_max']:.2%} (owner).")
    return "\n".join(hdr + D5.blind_plan_units()) + "\n"


def finalise(rdir: Path, cal2_tree: Path, blind_tree: Path, **kw) -> dict:
    import gate_d6 as G
    g, cal = G.evaluate(rdir, cal2_tree, blind_tree, **kw)
    if g["verdict"] != "GO":
        raise Refused("the launch gate reads NO-GO: " + "; ".join(g["why"]))
    terms = V5D.Terms.from_dict(g["terms"])
    law = V6D.Law(G._tuples(g["law"]))
    fz = FN.frozen(cal)
    fz["bars"] = dict(D6.BARS_OWNER)
    fz["model"] = {"name": "v6d", "module": "scripts/r3_timing_model_v6d.py", "fixes": V4DP.ALL.as_dict(),
                   "terms": terms.as_dict(), "law": law.as_dict(), "form": V6D.describe() | {"W, R": V4DP.describe()}}
    fz["g3d_label"] = ("DESCRIPTIVE (addendum 3, owner 2026-11-03; kept by addenda 5 and 6): computed as registered and "
                       "reported per model; never voids a model's certification. G3-D shuffle voids as registered")
    with D6.v6d(terms, law), D3.v4dp(V4DP.ALL), D5.blind5():
        rows = FN.predict(fz, models=D6.NEW_BLIND)
        desc = sorted("/".join(k) for k in D2.excluded_keys(D6.NEW_BLIND))
    return {"what": f"the new blind rental's predictions, finalised mechanically under {D6.NAME}",
            "addendum": D6.NAME, "frozen": fz, "cells": rows, "not_priced": sum(1 for r in rows if r["ms"]["v4d"] is None),
            "scope": D3.SCOPE, "descriptive_cells": desc, "GATE": g,
            "keys": "ms['v4d'] holds v6d's time (the frozen scorers read that key); every rival priced by v6d with the "
                    "rival's own change (rho other, NAIVE-NODEDUP, eager), roofline, line and OLS as frozen"}


def main(argv=None) -> int:
    a = list(argv if argv is not None else sys.argv[1:])
    plan_out = None
    if "--plan-out" in a:
        i = a.index("--plan-out")
        plan_out = Path(a[i + 1])
        del a[i:i + 2]
    if len(a) != 4:
        print(__doc__)
        return 2
    try:
        doc = finalise(Path(a[0]), Path(a[1]), Path(a[2]))
    except Refused as exc:
        print(f"REFUSED: {exc}")
        return 2
    Path(a[3]).write_text(json.dumps(doc, indent=1, default=str) + "\n")
    print(f"wrote {a[3]}: {len(doc['cells'])} cells, {doc['not_priced']} not priced, rho {doc['frozen']['rho_form']}, "
          f"model v6d, {len(doc['descriptive_cells'])} DESCRIPTIVE, gate {doc['GATE']['verdict']}")
    if plan_out is not None:
        plan_out.write_text(blind_plan(doc["frozen"]))
        print(f"wrote {plan_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
