#!/usr/bin/env python
"""Rental B2's predictions, finalised MECHANICALLY from tile rental A2's scored selections at A2's lock
(registration 2026-10-20-tileB2-e1tile): scripts/scoring/tileA/finalise.py run unchanged inside
a2common.scoring at L (v4 at L by P1's rule, v4 itself at 1710; the registration names A2's), and rental B2's
plan for A2's driver.

    python scripts/scoring/tileA2/finalise_a2.py <repo> <A2 score dir> <out.json> [--plan-out scripts/plans/rentalB2-tile-2026-10.plan]

THE LOCK AND THE POWER LIMIT (the owner's decision of 2026-10-20): rental B2 runs at the lock rung A2 held and
the GPU power limit A2 ran at, both read from A2's score directory (session.score.json, score_session_a2.py),
never from an argument. REFUSES (exit 2, nothing written) when session.score.json is missing or NOT READ, when
floor.score.json or e1cal.score.json (both required) or census, bytes or rep (when present) names another lock
than the session's (a score directory of another
run), unless A2's stop rule (tileB2-stop) reads GO, and when A2's merged census refused.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import a2common as A2  # noqa: E402

FN = A2.TC._load("finalise", A2.TILEA / "finalise.py")
TC = A2.TC
Refused = FN.Refused


def run_of(score_dir: Path) -> tuple[float, int]:
    """(lock, power limit W) of the A2 run whose scores `score_dir` holds; Refused on any disagreement."""
    s = A2.read_score(score_dir, "session")
    if s is None or s.get("verdict") != "READ":
        raise Refused(f"no READ session.score.json in {score_dir} ({(s or {}).get('verdict', 'missing')}): run score_session_a2.py")
    lock, pw = float(s["lock_mhz"]), int(round(float(s["power_limit_w"])))
    for part in ("census", "floor", "bytes", "rep", "e1cal"):
        d = A2.read_score(score_dir, part)
        if d is None and part in ("census", "bytes", "rep"):
            continue                      # absent is allowed (rep dropped; finalise's own fallbacks), present must match
        d = d or {}
        if d.get("lock_mhz") is None or float(d["lock_mhz"]) != lock:
            raise Refused(f"{part}.score.json names lock {d.get('lock_mhz')}, the session {lock:g}: not one run's scores")
    if pw not in (700, 900):
        raise Refused(f"the session's power limit {pw} W is not a registered limit (700 or 900)")
    return lock, pw


def finalise(repo: Path, score_dir: Path) -> dict:
    lock, pw = run_of(score_dir)
    with A2.scoring(A2.Rules.tileA2(lock)):
        doc = FN.finalise(repo, score_dir)
    fl = A2.read_score(score_dir, "floor") or {}
    doc["what"] = (f"rental B2's predictions at A2's lock {lock:g} MHz and {pw} W, finalised mechanically from A2's "
                   "selections (tileB2-e1tile; finalise.py inside a2common.scoring)")
    doc["a2"] = {"lock_mhz": lock, "power_limit_w": pw, "band_in_force": fl.get("band_in_force"),
                 "registration": A2.NAMES_A2["e1tile"],
                 "v4": (f"r3_timing_model_v4L.at_lock({lock:g}): c x 1710 / {lock:g} at every tile (P1's rule)"
                        if lock != A2.FIT_CLOCK_MHZ else "v4 itself (at_lock(1710) is the identity)")}
    return doc


def plan_b2(sel: dict, lock: float, power_w: int) -> str:
    """finalise.plan_b's unit lines unchanged; the header and the prelude line A2's."""
    text = FN.plan_b(sel)
    reps = (("# RENTAL B OF THE TILE STAGE: the blind test at the tile vLLM picks (registration 2026-10-14-tileB-e1tile).",
             f"# RENTAL B2 OF THE TILE STAGE: the blind test at the tile vLLM picks, at tile rental A2's lock {lock:g} MHz "
             f"and {power_w} W (registration {A2.NAMES_A2['e1tile']})."),
            ("# GENERATED by scripts/scoring/tileA/finalise.py from the frozen unit list; do not edit by hand.",
             "# GENERATED by scripts/scoring/tileA2/finalise_a2.py (finalise.plan_b, its header rewritten); do not edit by hand."),
            (f"--plan {FN.PLAN_B} --driver gh200_tile_session.sh", f"--plan {A2.PLAN_B2} --driver gh200_tileA2_session.sh"),
            ("- prelude est=3 cap=15", f"- prelude lock-mhz={int(round(lock))} power-limit-w={int(power_w)} est=3 cap=15"))
    for old, new in reps:
        if old not in text:
            raise Refused(f"finalise.plan_b no longer writes {old!r}: the B2 header cannot be rewritten mechanically")
        text = text.replace(old, new)
    return text


def main(argv=None) -> int:
    a = list(argv if argv is not None else sys.argv[1:])
    plan_out = None
    if "--plan-out" in a:
        i = a.index("--plan-out")
        if i + 1 >= len(a):
            print(__doc__)
            return 2
        plan_out = Path(a[i + 1])
        del a[i:i + 2]
    if len(a) != 3 or any(x.startswith("--") for x in a):
        print(__doc__)
        return 2
    repo, scores, out = Path(a[0]), Path(a[1]), Path(a[2])
    try:
        doc = finalise(repo, scores)
        lock, pw = doc["a2"]["lock_mhz"], doc["a2"]["power_limit_w"]
        plan = plan_b2(doc["selections"], lock, pw) if plan_out is not None else None
    except Refused as exc:
        print(f"REFUSED: {exc}")
        return 2
    out.write_text(json.dumps(doc, indent=1, default=str) + "\n")
    print(f"wrote {out}: {len(doc['cells'])} rows at {lock:g} MHz and {pw} W, key {doc['selections']['key']}, host cut {doc['host_cut']}")
    if plan is not None:
        plan_out.write_text(plan)
        print(f"wrote {plan_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
